def set_spacing(p, line=1.5, sb=0, sa=0):
    pPr = p._p.get_or_add_pPr()
    for old in pPr.findall(qn('w:spacing')):
        pPr.remove(old)
    sp = OxmlElement('w:spacing')
    sp.set(qn('w:line'), str(int(line * 240)))
    sp.set(qn('w:lineRule'), 'auto')
    sp.set(qn('w:before'), str(int(sb * 20)))
    sp.set(qn('w:after'), str(int(sa * 20)))
    pPr.append(sp)


def add_run(p, text, bold=False, color=None):
    run = p.add_run(text)
    run.bold = bold
    run.font.name = 'Times New Roman'
    run.font.size = Pt(14)
    if color:
        run.font.color.rgb = RGBColor(*color)
    rPr = run._r.get_or_add_rPr()
    rf = OxmlElement('w:rFonts')
    rf.set(qn('w:ascii'), 'Times New Roman')
    rf.set(qn('w:hAnsi'), 'Times New Roman')
    rf.set(qn('w:cs'), 'Times New Roman')
    for old in rPr.findall(qn('w:rFonts')):
        rPr.remove(old)
    rPr.insert(0, rf)
    return run


def new_para(indent=True, center=False, left_cm=0, sb=0, sa=0):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.JUSTIFY
    pf = p.paragraph_format
    pf.first_line_indent = Cm(1.25) if indent else Pt(0)
    pf.left_indent = Cm(left_cm) if left_cm else Pt(0)
    pf.space_before = Pt(0)
    pf.space_after = Pt(0)
    set_spacing(p, sb=sb, sa=sa)
    return p


def bullet(text):
    p = new_para(indent=False, left_cm=1.25)
    add_run(p, '– ' + text)
    return p


def fig(n, caption):
    p1 = new_para(indent=False, center=True, sb=3)
    add_run(p1, f'[ Вставьте скриншот — Рисунок {n} ]', color=(130, 130, 130))
    p2 = new_para(indent=False, center=True, sa=3)
    add_run(p2, f'Рисунок {n} – {caption}')


def subheading(text):
    p = new_para(indent=False, sb=4, sa=0)
    add_run(p, text, bold=True)
    return p


